"""Fix login screen after a successful /acesso/<key> redirect on hosted Motion Studio.

Idempotent patch for source generated by bootstrap.py.
"""
from pathlib import Path

server = Path('app/server.py')
frontend = Path('static/app.js')

old_server = '''@app.get("/api/access")
def access():
    return {"password_required": bool(ACCESS_TOKEN)}'''
new_server = '''@app.get("/api/access")
def access(request: Request):
    """Report authentication status without disclosing the access key."""
    authenticated = (not ACCESS_TOKEN or hmac.compare_digest(
        request.cookies.get("motion_session", ""),
        hashlib.sha256(ACCESS_TOKEN.encode("utf-8")).hexdigest()
    ))
    return {"password_required": bool(ACCESS_TOKEN), "authenticated": authenticated}'''

source = server.read_text(encoding='utf-8')
if old_server in source:
    server.write_text(source.replace(old_server, new_server, 1), encoding='utf-8')
elif new_server not in source:
    raise SystemExit('Unexpected server access handler; refusing to patch')

js_source = frontend.read_text(encoding='utf-8')
old_js = 'if(access.password_required){'
new_js = 'if(access.password_required && !access.authenticated){'
if old_js in js_source:
    frontend.write_text(js_source.replace(old_js, new_js, 1), encoding='utf-8')
elif new_js not in js_source:
    raise SystemExit('Unexpected frontend boot handler; refusing to patch')

print('Private-link auto-login patch installed')
